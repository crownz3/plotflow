  /**
   * Prospective client requests a site visit from a shared link
   */
  async bookSiteVisit(shareId: string, clientData: {
    clientName: string;
    clientPhone: string;
    preferredDate: string;
    preferredSlot: string;
    notes?: string;
  }): Promise<PublicSiteVisitBooking> {
    let link: SecureSharedLink | null | undefined = this.tenantShareLinks().find(l => l.id === shareId);
    if (!link) {
      link = await this.getPublicShareLink(shareId);
    }
    if (!link) {
      throw new Error('Property share link could not be located.');
    }

    const randomHex = Math.random().toString(36).substring(2, 9);
    const bookingId = `sv_${randomHex}`;
    const now = Date.now();

    const rawImg = link.propertySnapshot.images?.[0] || '';
    // Guard against oversized Base64 data URLs exceeding Firestore string limits (max 500 chars in security rule)
    const safeImage = (rawImg.startsWith('http://') || rawImg.startsWith('https://')) && rawImg.length <= 500
      ? rawImg
      : '';

    const booking: PublicSiteVisitBooking = {
      id: bookingId,
      tenantId: link.tenantId || this.auth.activeTenantId() || 'tenant_default',
      shareLinkId: link.id,
      propertyId: link.propertyId,
      propertyTitle: (link.propertyTitle || 'Property').slice(0, 200),
      propertyLocation: `${link.propertySnapshot.locality || ''}, ${link.propertySnapshot.city || ''}`.replace(/^, /, '').slice(0, 200) || 'Prime Location',
      propertyImage: safeImage,
      clientName: clientData.clientName.trim().slice(0, 100),
      clientPhone: clientData.clientPhone.trim().slice(0, 25),
      preferredDate: clientData.preferredDate.slice(0, 50),
      preferredSlot: clientData.preferredSlot.slice(0, 50),
      notes: (clientData.notes || '').trim().slice(0, 1000),
      agencyName: (link.agencyName || 'PlotFlow Real Estate').slice(0, 100),
      agencyPhone: (link.agencyPhone || '+91 98765 43210').slice(0, 25),
      assignedAgentName: link.agentName ? link.agentName.slice(0, 100) : undefined,
      assignedAgentPhone: link.agentPhone ? link.agentPhone.slice(0, 25) : undefined,
      status: 'pending',
      createdAt: now,
      updatedAt: now
    };

    // Cache locally for instant UX
    this.siteVisitBookings.update(list => [booking, ...list]);
    try {
      if (typeof localStorage !== 'undefined') {
        localStorage.setItem(`pf_visit_booking_${bookingId}`, JSON.stringify(booking));
      }
    } catch {}

    // Save to Firestore /site_visit_bookings/{bookingId}
    try {
      const docRef = doc(this.firebase.firestore, 'site_visit_bookings', bookingId);
      const payload = sanitizeForFirestore(booking);
      await setDoc(docRef, payload);
      console.log('Site visit booking persisted to Firestore successfully:', bookingId);
    } catch (err: any) {
      console.error('CRITICAL: Firestore setDoc failed for site visit booking:', err);
    }

    // Auto-create Inbound CRM Lead
    try {
      await this.leadService.addLead({
        tenantId: link.tenantId,
        name: clientData.clientName.trim(),
        phone: clientData.clientPhone.trim(),
        source: 'direct_call',
        stage: 'contacted',
        priority: 'hot',
        requirement: {
          propertyTypes: [link.propertySnapshot.propertyType],
          listingType: (link.propertySnapshot.listingType === 'lease' ? 'rent' : link.propertySnapshot.listingType) as 'sale' | 'rent',
          budgetMin: link.propertySnapshot.price ? link.propertySnapshot.price * 0.9 : 5000000,
          budgetMax: link.propertySnapshot.price ? link.propertySnapshot.price * 1.1 : 15000000,
          preferredLocations: [link.propertySnapshot.locality || link.propertySnapshot.city]
        },
        assignedAgentName: link.agentName
      });
    } catch (e) {
      console.warn('Could not auto-add lead for site visit:', e);
    }

    return booking;
  }

  /**
   * Fetches public site visit booking by ID (Universal: no auth required)
   */
  async getSiteVisitBooking(bookingId: string): Promise<PublicSiteVisitBooking | null> {
    try {
      const docRef = doc(this.firebase.firestore, 'site_visit_bookings', bookingId);
      const snap = await getDoc(docRef);
      if (snap.exists()) {
        return {
          ...(snap.data() as PublicSiteVisitBooking),
          id: snap.id
        };
      }
    } catch (err) {
      console.warn('Error fetching site visit booking, trying cache:', err);
    }

    // LocalStorage fallback cache
    try {
      if (typeof localStorage !== 'undefined') {
        const cached = localStorage.getItem(`pf_visit_booking_${bookingId}`);
        if (cached) return JSON.parse(cached) as PublicSiteVisitBooking;
      }
    } catch {}

    return null;
  }

  /**
   * Listen to a specific site visit booking in real time (e.g. shows rescheduled or confirmed live)
   */
  bindSiteVisitListener(
    bookingId: string,
    callback: (booking: PublicSiteVisitBooking | null) => void
  ): Unsubscribe {
    const docRef = doc(this.firebase.firestore, 'site_visit_bookings', bookingId);
    return onSnapshot(
      docRef,
      snap => {
        if (snap.exists()) {
          const data = {
            ...(snap.data() as PublicSiteVisitBooking),
            id: snap.id
          };
          try {
            if (typeof localStorage !== 'undefined') {
              localStorage.setItem(`pf_visit_booking_${bookingId}`, JSON.stringify(data));
            }
          } catch {}
          callback(data);
          return;
        }

        // Fallback to localStorage if cloud doc not yet returned
        try {
          if (typeof localStorage !== 'undefined') {
            const cached = localStorage.getItem(`pf_visit_booking_${bookingId}`);
            if (cached) {
              callback(JSON.parse(cached) as PublicSiteVisitBooking);
              return;
            }
          }
        } catch {}

        callback(null);
      },
      err => {
        console.warn('Error listening to site visit booking:', err);
        try {
          if (typeof localStorage !== 'undefined') {
            const cached = localStorage.getItem(`pf_visit_booking_${bookingId}`);
            if (cached) {
              callback(JSON.parse(cached) as PublicSiteVisitBooking);
              return;
            }
          }
        } catch {}
        callback(null);
      }
    );
  }

  /**
   * Agency Admin confirms a requested site visit
   */
  async confirmSiteVisitBooking(
    bookingId: string,
    scheduledTime: number,
    agentName?: string,
    agentPhone?: string
  ): Promise<void> {
    const now = Date.now();
    const updates: Partial<PublicSiteVisitBooking> = {
      status: 'confirmed',
      scheduledTime,
      updatedAt: now
    };
    if (agentName) updates.assignedAgentName = agentName;
    if (agentPhone) updates.assignedAgentPhone = agentPhone;

    // Local optimistic update
    this.siteVisitBookings.update(list =>
      list.map(b => (b.id === bookingId ? { ...b, ...updates } : b))
    );

    const docRef = doc(this.firebase.firestore, 'site_visit_bookings', bookingId);
    await updateDoc(docRef, updates);
  }

  /**
   * Agency Admin reschedules a site visit (client's link updates in real time!)
   */
  async rescheduleSiteVisitBooking(
    bookingId: string,
    newDate: string,
    newSlot: string,
    scheduledTime: number,
    rescheduledReason: string
  ): Promise<void> {
    const now = Date.now();
    const updates: Partial<PublicSiteVisitBooking> = {
      status: 'rescheduled',
      preferredDate: newDate,
      preferredSlot: newSlot,
      scheduledTime,
      rescheduledReason: rescheduledReason.trim() || 'Schedule updated to match property owner availability.',
      updatedAt: now
    };

    // Local optimistic update
    this.siteVisitBookings.update(list =>
      list.map(b => (b.id === bookingId ? { ...b, ...updates } : b))
    );

    const docRef = doc(this.firebase.firestore, 'site_visit_bookings', bookingId);
    await updateDoc(docRef, updates);
  }
